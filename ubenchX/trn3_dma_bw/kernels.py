@nki.jit
def store_static_kernel(in_shape_tensor):
    num_transfers = in_shape_tensor.shape[0]
    P = in_shape_tensor.shape[1]
    F = in_shape_tensor.shape[2]
    out_tensor = nl.ndarray([num_transfers, P, F], buffer=nl.shared_hbm, dtype=in_shape_tensor.dtype)

    sb_tensor = nl.ndarray([P, F], dtype=in_shape_tensor.dtype, buffer=nl.sbuf, address=(0, 0))
    nisa.memset(dst=sb_tensor, value=FILL_VALUE)

    with nl.no_reorder():
        for i in nl.static_range(num_transfers):
            nisa.dma_copy(dst=out_tensor[i, :, :], src=sb_tensor, dge_mode=dge_mode_enum.none)

    return out_tensor


