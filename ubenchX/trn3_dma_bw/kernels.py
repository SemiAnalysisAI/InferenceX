"""Trainium3 DMA bandwidth kernels (NKI 0.7), one NeuronCore at LNC=1.

Each kernel is a single burst of nisa.dma_copy instructions:

  load_*   HBM -> SBUF. in_tensor is [num_transfers, P, F]; transfer i copies in_tensor[i] ([P, F])
           into one of a ring of SBUF slots. After the burst, a short reduce over the ring slots
           keeps the loaded data live, so the kernel is almost pure DMA.
  store_*  SBUF -> HBM. One [P, F] SBUF tile is written to each of num_transfers slices of the
           [num_transfers, P, F] output. No compute.

  *_static   descriptors generated before execution and stored in HBM (dge_mode=none)
  *_hwdge    descriptors generated by the DGE hardware block at run time (dge_mode=hwdge)
  *_swdge    descriptors generated by the GpSimd engine at run time (dge_mode=swdge)

The three variants of each direction differ only in dge_mode.
"""

import nki
import nki.isa as nisa
import nki.language as nl
from nki.isa.constants import dge_mode as dge_mode_enum

DTYPE_SIZE = 2
SBUF_RING_BYTES = 192000  # per-partition SBUF bytes used for the load ring
FILL_VALUE = 42.42


@nki.jit
def load_static_kernel(in_tensor):
    num_transfers = in_tensor.shape[0]
    P = in_tensor.shape[1]
    F = in_tensor.shape[2]
    out_tensor = nl.ndarray([P, F], dtype=in_tensor.dtype, buffer=nl.shared_hbm)

    tile_bytes = F * DTYPE_SIZE
    n_slots = min(SBUF_RING_BYTES // tile_bytes, num_transfers)
    slots = []
    for t in range(n_slots):
        slots.append(nl.ndarray([P, F], dtype=in_tensor.dtype, buffer=nl.sbuf, address=(0, t * tile_bytes)))
    acc = nl.ndarray([P, F], dtype=in_tensor.dtype, buffer=nl.sbuf, address=(0, n_slots * tile_bytes))
    nisa.memset(dst=acc, value=0.0)

    with nl.no_reorder():
        for i in nl.static_range(num_transfers):
            nisa.dma_copy(dst=slots[(num_transfers - i - 1) % n_slots], src=in_tensor[i, :, :],
                          dge_mode=dge_mode_enum.none)
        for t in nl.static_range(n_slots):
            nisa.tensor_tensor(dst=acc, data1=acc, data2=slots[t], op=nl.add)

    nl.store(out_tensor, value=acc)
    return out_tensor


